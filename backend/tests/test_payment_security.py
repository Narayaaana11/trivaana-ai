"""
TRIVAANA AI: Payment & Wallet Security Regression Tests
Validates:
1. Server-side payment order recording with tenant ownership and integer paise.
2. Rejection of client amount tampering (wallet credited strictly from recorded server order).
3. Cross-tenant order verification rejection (HTTP 403).
4. Invalid payment signature rejection (HTTP 400).
5. Raw-body Razorpay webhook HMAC-SHA256 signature verification.
6. Webhook idempotency across duplicate event deliveries.
7. Disabling of sandbox top-up in production environments.
"""

import hmac
import hashlib
import json
import pytest
from core.config import settings

def test_server_order_recording_and_amount_tamper_protection(client, demo_auth_headers):
    """
    Client creates an order for ₹500 (50,000 paise).
    During checkout verification, a malicious client sends amount_inr: 50,000.
    The server MUST credit only 50,000 paise (₹500), strictly derived from recorded order.
    """
    # 1. Fetch initial wallet balance
    init_tenant = client.get("/api/tenant", headers=demo_auth_headers).json()
    initial_balance_paise = init_tenant["wallet_balance_paise"]

    # 2. Create order for ₹500.00
    order_resp = client.post("/api/billing/razorpay-order", headers=demo_auth_headers, json={
        "amount_inr": 500.0
    })
    assert order_resp.status_code == 200
    order = order_resp.json()
    order_id = order["id"]
    assert order["amount"] == 50000

    # 3. Simulate client callback attempting to inflate amount to ₹50,000
    pay_id = f"pay_sandbox_{order_id[-8:]}"
    verify_resp = client.post("/api/billing/razorpay-verification", headers=demo_auth_headers, json={
        "order_id": order_id,
        "payment_id": pay_id,
        "signature": "valid_signature_sandbox",
        "amount_inr": 50000.0  # Attempted 100x manipulation
    })
    assert verify_resp.status_code == 200
    credit_res = verify_resp.json()

    # Verify credited amount is exactly 50,000 paise (₹500), NOT manipulated 50,000 INR
    assert credit_res["amount_paise"] == 50000
    assert credit_res["amount_inr"] == 500.0

    # 4. Verify updated tenant wallet balance
    updated_tenant = client.get("/api/tenant", headers=demo_auth_headers).json()
    assert updated_tenant["wallet_balance_paise"] == initial_balance_paise + 50000

def test_foreign_tenant_order_rejection(client, demo_auth_headers, second_tenant_auth_headers):
    """Tenant B must never be able to claim or credit an order generated by Tenant A."""
    # 1. Tenant A generates order
    order_resp = client.post("/api/billing/razorpay-order", headers=demo_auth_headers, json={
        "amount_inr": 1000.0
    })
    assert order_resp.status_code == 200
    order_id = order_resp.json()["id"]

    # 2. Tenant B attempts to verify and credit Tenant A's order -> 403 Forbidden
    pay_id = f"pay_sandbox_{order_id[-8:]}"
    tamper_resp = client.post("/api/billing/razorpay-verification", headers=second_tenant_auth_headers, json={
        "order_id": order_id,
        "payment_id": pay_id,
        "signature": "valid_signature_sandbox"
    })
    assert tamper_resp.status_code == 403
    assert "belongs to another tenant" in tamper_resp.json()["detail"].lower()

def test_razorpay_raw_webhook_signature_and_idempotency(client, demo_auth_headers):
    """
    Tests raw body webhook processing:
    1. Valid HMAC-SHA256 signature over raw bytes credits tenant wallet.
    2. Invalid signature is rejected with HTTP 400.
    3. Duplicate event delivery is idempotent and does not double-credit wallet.
    """
    # 1. Create order
    order_resp = client.post("/api/billing/razorpay-order", headers=demo_auth_headers, json={
        "amount_inr": 750.0
    })
    order_id = order_resp.json()["id"]

    # Setup webhook secret for test
    webhook_secret = "test_webhook_secret_key_12345"
    settings.RAZORPAY_WEBHOOK_SECRET = webhook_secret

    pay_id = f"pay_live_test_{order_id[-8:]}"
    webhook_payload = {
        "event": "payment.captured",
        "payload": {
            "payment": {
                "entity": {
                    "id": pay_id,
                    "order_id": order_id,
                    "amount": 75000,
                    "currency": "INR",
                    "status": "captured"
                }
            }
        }
    }
    raw_body = json.dumps(webhook_payload).encode("utf-8")

    # 2. Test Invalid Webhook Signature -> 400 Bad Request
    invalid_resp = client.post(
        "/api/billing/razorpay-webhook",
        content=raw_body,
        headers={
            "Content-Type": "application/json",
            "X-Razorpay-Signature": "invalid_forged_signature"
        }
    )
    assert invalid_resp.status_code == 400
    assert "invalid webhook signature" in invalid_resp.json()["detail"].lower()

    # 3. Test Valid Webhook Signature
    valid_signature = hmac.new(
        webhook_secret.encode("utf-8"),
        raw_body,
        hashlib.sha256
    ).hexdigest()

    init_bal = client.get("/api/tenant", headers=demo_auth_headers).json()["wallet_balance_paise"]

    valid_resp = client.post(
        "/api/billing/razorpay-webhook",
        content=raw_body,
        headers={
            "Content-Type": "application/json",
            "X-Razorpay-Signature": valid_signature
        }
    )
    assert valid_resp.status_code == 200
    assert valid_resp.json()["status"] == "success"
    assert valid_resp.json()["amount_paise"] == 75000

    new_bal = client.get("/api/tenant", headers=demo_auth_headers).json()["wallet_balance_paise"]
    assert new_bal == init_bal + 75000

    # 4. Duplicate Webhook Delivery (Idempotency) -> Must NOT credit twice!
    duplicate_resp = client.post(
        "/api/billing/razorpay-webhook",
        content=raw_body,
        headers={
            "Content-Type": "application/json",
            "X-Razorpay-Signature": valid_signature
        }
    )
    assert duplicate_resp.status_code == 200
    assert duplicate_resp.json()["status"] == "already_processed"

    # Wallet balance must remain identical
    after_dup_bal = client.get("/api/tenant", headers=demo_auth_headers).json()["wallet_balance_paise"]
    assert after_dup_bal == new_bal

def test_sandbox_topup_disabled_in_production(client, demo_auth_headers, monkeypatch):
    """In production mode, /api/billing/sandbox-topup must return HTTP 403 Forbidden."""
    monkeypatch.setattr(settings, "ENVIRONMENT", "production")
    monkeypatch.setattr(settings, "ALLOW_SANDBOX_TOPUP", False)

    resp = client.post("/api/billing/sandbox-topup", headers=demo_auth_headers, json={
        "amount_inr": 500.0
    })
    assert resp.status_code == 403
    assert "strictly disabled in production" in resp.json()["detail"].lower()
